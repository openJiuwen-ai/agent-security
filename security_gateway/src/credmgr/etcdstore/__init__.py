"""The etcd-backed store for the credential router's multi-node control plane.

A thin layer over the etcd client that exposes only the verbs the rest of
the project needs — credential CRUD with compare-and-swap, a listing at a
known revision, the rotation lock, the handover, and the watch — and
nothing else.

**The keyspace is a contract.** The prefixes and the value encodings are
frozen by the design document, because every node in a cluster reads what
the others wrote.  A change here needs a change on both sides.

**A rejected compare-and-swap is not an error.** The verdict is the
``succeeded`` boolean a transaction returns; a ``False`` means the
comparison did not hold and the value was **not** written.  Code that
treats that as a transport failure silently disables every optimistic lock
in the system.  See :mod:`security_gateway.credmgr.etcdstore.store`.

The etcd client itself is an optional extra, and it is imported lazily:
this package must import cleanly without ``etcd3`` installed.
"""

